/** الدرجة القصوى الممكنة (مجموع درجات جميع الأسئلة باستثناء الاسترشادية). */
export const MEAL_MAX_SCORE = MEAL_QUESTIONS.reduce((s, q) => s + (q.score || 0), 0);

/**
 * يحسب الدرجة الإجمالية لمجموعة إجابات.
 * - السؤال العادي:  «نعم» تمنح الدرجة
 * - السؤال السلبي:  «لا» تمنح الدرجة
 * - السؤال الاسترشادي (score: 0): لا يُحتسب أبداً
 */
export function computeMealScore(answers) {
  let total = 0;
  for (const q of MEAL_QUESTIONS) {
    if (!q.score) continue;
    const target = q.negative ? 'لا' : 'نعم';
    if (answers?.[q.id] === target) total += q.score;
  }
  return total;
}
